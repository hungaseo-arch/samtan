-- ============================================================
-- lifetimes.note 이어붙임 오류 정정
--
-- 20260827200000 이 사유를 덧쓸 때 구분자 없이 `note || '...'` 했다.
-- 기존 노트가 있던 DA12511H03160D 에서 두 문장이 붙어 버렸다.
--   '813 L3i' + '2026-08-06·08-07 …' → '813 L3i2026-08-06·08-07 …'
-- 화면에서는 '813 L3i2026-08-06·08-07 연속 교체 기재' 로 읽혀
-- 앞의 '813 L3i'(장착 차량·포지션 메모)가 날짜의 일부처럼 보였다.
--
-- 원인 마이그레이션도 같은 커밋에서 ' · ' 를 넣도록 고쳤다. 이 파일은
-- 이미 적재된 값을 되돌리기 위한 것이고, 정확히 붙은 형태일 때만 손댄다.
-- ============================================================

update public.lifetimes
   set note = '813 L3i · 2026-08-06·08-07 연속 교체 기재 — 원장 확인 대기'
 where serial = 'DA12511H03160D'
   and note = '813 L3i2026-08-06·08-07 연속 교체 기재 — 원장 확인 대기';

-- 같은 실수가 더 있는지 본다. 조각 사이에 공백도 구분자도 없이
-- 한글·숫자가 맞붙은 노트는 정상 입력에서 나오지 않는다.
do $$
declare v_bad int;
begin
  select count(*) into v_bad from public.lifetimes
   where note ~ '[A-Za-z0-9]2026-';
  if v_bad > 0 then
    raise exception '구분자 없이 붙은 note 가 %건 남아 있다', v_bad;
  end if;
end $$;

