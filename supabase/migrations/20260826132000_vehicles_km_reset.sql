-- ============================================================
-- B-3 · 주행거리 계기 교체/리셋 표시
--
-- km 에는 CHECK 제약을 걸지 않는다 (작업지시서 v2 §3).
-- 계기 교체·리셋으로 km 이 정당하게 줄어드는 경우가 있고, 현장에서
-- 저장이 막히면 점검 자체가 기록되지 않는 쪽이 더 큰 손실이다.
-- 감소·급증·결측은 전부 **경고만** 띄우고 저장은 허용한다.
--
-- vehicles.hm_reset 은 이미 있다 (t103). km 쪽만 추가한다.
--
-- 현재 알려진 이상치:
--   CH 847  2026-07-12 89,100.0 → 2026-07-26 135,397.1  (14일 46,297km = 3,307km/일)
--   CH 849  km 전량 0 (60행) — 계기 미기록
-- 둘 다 km_reset 으로 설명되는 사안이 아니므로 플래그는 세우지 않는다.
-- ============================================================

alter table public.vehicles
  add column if not exists km_reset boolean not null default false;

comment on column public.vehicles.km_reset is
  '주행거리계 교체·리셋 이력이 있는 차량. true 면 km 감소를 경고하지 않는다. hm_reset 과 짝.';

-- ── CH 834 · 2026-07-05 주행거리계 리셋 (작업지시서 v3 §0.6(a) · §C-2) ──
-- 리셋 이후 현장이 "KM Reset 카운터"를 누적값에 그대로 더해 기록해 왔다.
-- 증분이 아니라 카운터 전체를 더하므로 오차가 회차마다 누적된다.
--   올바른 누적 KM = 736,453.0 (06-14 시점 누적) + KM Reset 카운터
--     07-26  748,965.9 → 747,052.7   (+1,913.2 과대)
--     08-09  765,669.8 → 753,156.9   (+12,512.9 과대)
--     08-23  787,639.0 → 758,422.2   (+29,216.8 과대)
-- 값 자체의 정정은 Phase A·B 적재에서 km_corrected 로 처리한다 (사용자 승인 2026-08-27).
-- 여기서는 "이 차량은 계기 리셋 이력이 있다"는 사실만 표시해 km 감소 경고를 끈다.
update public.vehicles set km_reset = true where ch = '834' and km_reset = false;

